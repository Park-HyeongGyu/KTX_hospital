####################################

# =========================
# 0: 필요 라이브러리 & 설정
# =========================
library(sf)
library(osrm)

options(osrm.server = "http://localhost:5000/")
options(osrm.profile = "car")

# =========================
# 1. EPSG:5137 좌표 (출발점)
# =========================
# 예시: 임의 좌표 (5137)
src_5179 <- st_sfc(
  st_point(c(960000, 1950000)),  # 예시 좌표 (x, y)
  crs = 5179
)

src_5137 <- st_sf(id = "origin", geometry = src_5179)

# =========================
# 2. 도착점 (WGS84)
# =========================
dst_4326 <- st_as_sf(
  data.frame(id = "seoul_station", lon = 126.9723, lat = 37.5547),
  coords = c("lon", "lat"),
  crs = 4326
)

# =========================
# 3. OSRM용으로 변환
# =========================
src_4326 <- st_transform(src_5137, 4326)

# =========================
# 4. snap - 오류 줄이기, 가장 가까운 도로 찍기
# =========================
src_4326 <- osrmNearest(src_4326)
dst_4326 <- osrmNearest(dst_4326)

# =========================
# 5. route 계산
# =========================
res <- osrmRoute(
  src = src_4326,
  dst = dst_4326,
  overview = FALSE
)

print(res)
